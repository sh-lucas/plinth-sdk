import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { generate, PlinthClient, type Template } from "../src/index.js";
import { createFixture, createPointsModel, hasServer } from "./fixture.js";

const run = (cmd: string, args: string[], env = process.env) => execFileSync(cmd, args, { cwd: new URL("..", import.meta.url), env, encoding: "utf8" });

describe("generate", () => {
  it("names types and collects guard codes from require and allocate.require", () => {
    const t: Template = {
      id: "sell-v1", domain: "d", name: "n", disabled: false, created_at: "",
      nodes: [
        { id: "qty", op: "input", value_type: "integer" },
        { id: "lot", op: "input", value_type: "reference" },
        { id: "g", op: "require", condition: "c", code: "B_CODE" },
        { id: "a", op: "allocate", require: { code: "A_CODE" } },
      ],
    };
    const src = generate([t]);
    expect(src).toContain('export type SellV1Inputs = {\n  "qty": number | bigint;\n  "lot": string;\n};');
    expect(src).toContain('export type SellV1Rejection = "A_CODE" | "B_CODE";');
    expect(src).toContain("sellV1: {");
  });
});

describe.skipIf(!hasServer)("plinth gen CLI", () => {
  it("generates a module for the local server that type-checks", async () => {
    const fx = await createFixture();
    const m = await createPointsModel(fx);
    run("pnpm", ["exec", "tsc", "-p", "tsconfig.build.json"]);

    mkdirSync(new URL("./.gen/", import.meta.url), { recursive: true });
    const dir = new URL("./.gen/", import.meta.url).pathname;
    const out = `${dir}plinth.gen.ts`;
    run("node", ["dist/cli.js", "gen", "--url", fx.url, "--email", fx.email, "--password", fx.password, "--out", out, "--sdk", "../../src/index.js", m.credit, m.redeem]);

    const src = readFileSync(out, "utf8");
    expect(src).toContain("Generated by `plinth gen`");
    expect(src).toContain('"INSUFFICIENT_POINTS"');

    const key = (id: string) => id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase()).replace(/^(\d)/, "t$1");
    writeFileSync(
      `${dir}usage.ts`,
      `import { PlinthClient } from "../../src/index.js";
import { createTemplates } from "./plinth.gen.js";
const t = createTemplates(new PlinthClient({ baseUrl: "http://x" }));
export const ok = t.${key(m.redeem)}.execute({ inputs: { amount: 5n }, idempotencyKey: "k", context: { bucket: "a" } });
// @ts-expect-error amount is required
t.${key(m.redeem)}.execute({ inputs: {}, idempotencyKey: "k" });
// @ts-expect-error unknown input
t.${key(m.credit)}.preview({ inputs: { amount: 1, other: 2 } });
// @ts-expect-error amount is a number
t.${key(m.credit)}.preview({ inputs: { amount: "1" } });
t.${key(m.redeem)}.isRejection(new Error("x"), "INSUFFICIENT_POINTS");
// @ts-expect-error not a guard code of this template
t.${key(m.redeem)}.isRejection(new Error("x"), "OTHER");
`,
    );
    run("pnpm", ["exec", "tsc", "--noEmit", "--strict", "--module", "nodenext", "--moduleResolution", "nodenext", "--target", "es2022", "--lib", "es2022,dom", "--types", "node", "--skipLibCheck", `${dir}usage.ts`]);

    // The generated wrapper really runs.
    await fx.admin.buckets.create(m.domain, { id: fx.id("gen-alice") });
    const mod = await import(/* @vite-ignore */ out);
    const t = mod.createTemplates(new PlinthClient({ baseUrl: fx.url, credentials: { email: fx.email, password: fx.password } }));
    const tx = await t[key(m.credit)].execute({ inputs: { amount: 7 }, context: { bucket: fx.id("gen-alice") }, idempotencyKey: `gen:${fx.runid}` });
    expect(tx.postings[0].amount).toBe(7);
  });
});
