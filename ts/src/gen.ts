import type { InputNode, Template } from "./types.js";

const words = (id: string) => id.split(/[^A-Za-z0-9]+/).filter(Boolean);
const pascal = (id: string) => words(id).map((w) => w[0]!.toUpperCase() + w.slice(1)).join("");
const camel = (id: string) => {
  const p = pascal(id);
  const c = p[0]!.toLowerCase() + p.slice(1);
  return /^[0-9]/.test(c) ? "t" + p : c;
};
const typeName = (id: string) => (/^[0-9]/.test(pascal(id)) ? "T" : "") + pascal(id);

function guardCodes(t: Template): string[] {
  const codes = new Set<string>();
  for (const n of t.nodes) {
    if (n.op === "require" && typeof n.code === "string") codes.add(n.code);
    const req = n.op === "allocate" ? (n.require as { code?: string } | undefined) : undefined;
    if (req?.code) codes.add(req.code);
  }
  return [...codes].sort();
}

function inputsType(t: Template): string {
  const fields = t.nodes
    .filter((n): n is InputNode => n.op === "input")
    .map((n) => {
      const ty = n.value_type === "integer" ? "number | bigint" : n.value_type === "boolean" ? "boolean" : "string";
      return `  ${JSON.stringify(n.id)}: ${ty};`;
    });
  return fields.length ? `{\n${fields.join("\n")}\n}` : "Record<string, never>";
}

/** Render a TypeScript module with typed inputs, rejection codes and wrappers for the templates. */
export function generate(templates: Template[], sdkModule = "@plinth/sdk"): string {
  const out: string[] = [
    "// Generated by `plinth gen`. Do not edit.",
    "// Safe to keep in version control: template ids are immutable, so this file never goes stale.",
    `import { isRejection, type PlinthClient, type ExecuteOptions, type PreviewOptions } from ${JSON.stringify(sdkModule)};`,
    "",
  ];
  for (const t of templates) {
    const n = typeName(t.id);
    const codes = guardCodes(t);
    out.push(`/** Inputs of template ${JSON.stringify(t.id)}. */`);
    out.push(`export type ${n}Inputs = ${inputsType(t)};`);
    out.push(`/** Guard codes that template ${JSON.stringify(t.id)} can reject with. */`);
    out.push(`export type ${n}Rejection = ${codes.length ? codes.map((c) => JSON.stringify(c)).join(" | ") : "never"};`, "");
  }
  out.push("export function createTemplates(client: PlinthClient) {", "  return {");
  for (const t of templates) {
    const n = typeName(t.id);
    const id = JSON.stringify(t.id);
    out.push(
      `    ${camel(t.id)}: {`,
      `      execute: (o: Omit<ExecuteOptions, "inputs"> & { inputs: ${n}Inputs }) => client.execute(${id}, o),`,
      `      preview: (o: Omit<PreviewOptions, "inputs"> & { inputs: ${n}Inputs }) => client.preview(${id}, o),`,
      `      isRejection: (err: unknown, code?: ${n}Rejection) => isRejection(err, code),`,
      "    },",
    );
  }
  out.push("  };", "}", "");
  return out.join("\n");
}
